export type Key = keyof typeof en;
const dicts: Record<Lang, Dict> = { en, ar };

type Ctx = { lang: Lang; dir: "rtl" | "ltr"; t: (k: Key) => string; setLang: (l: Lang) => void };
const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");
  useEffect(() => {
    let initial: Lang = "ar";
    try {
      const saved = localStorage.getItem("murailex.lang");
      if (saved === "ar" || saved === "en") initial = saved;
      else if (!navigator.language.toLowerCase().startsWith("ar")) initial = "en";
    } catch {
      /* storage unavailable */
    }
    // eslint-disable-next-line react-hooks/set-state-in-effect -- hydrate the persisted preference once on mount
    setLangState(initial);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("murailex.lang", l);
    } catch {
      /* storage unavailable */
    }
  }, []);
  const value = useMemo<Ctx>(
    () => ({ lang, dir: lang === "ar" ? "rtl" : "ltr", t: (k) => dicts[lang][k] ?? en[k], setLang }),
    [lang, setLang],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n outside provider");
  return ctx;
}

export const dictionaries = dicts;
